//! OSM basemap (P4): extract of the Protomaps daily planet build for the site box.
//!
//! The extract reads the 139 GB planet archive by HTTP range requests through the shared
//! downloader ([`crate::build::extract`]: each range is its own cache entry, the tile
//! ranges are merged). The result is kept in `data/cache/protomaps/extracts/` and reused
//! while the build key, the box and the zoom do not change. The build list, the sprite
//! and the glyphs go through the downloader too.
//!
//! Licence: ODbL, « Produced Work » of OpenStreetMap; attribution Protomaps and
//! OpenStreetMap contributors (report 03).

use std::path::{Path, PathBuf};
use std::time::Duration;

use serde_json::Value;
use skimap_common::download::{Downloader, Request};
use skimap_common::layout::DataLayout;
use skimap_common::site::Site;

use crate::build::extract::{ExtractStats, HttpRanges};
use crate::build::{assets, copy_file, create_dir, dir_size, source, write_bytes};
use crate::error::{Error, Result};
use crate::manifest::Basemap;
use crate::reader::TileArchive;

/// Downloader source of the build list.
pub const SOURCE: &str = "protomaps";
/// Downloader source of the style assets (GitHub Pages).
pub const ASSETS_SOURCE: &str = "protomaps-assets";
/// List of the daily builds.
pub const BUILDS_URL: &str = "https://build-metadata.protomaps.dev/builds.json";
/// Base URL of the builds.
pub const BUILD_BASE: &str = "https://build.protomaps.com/";
/// Fonts and sprites of `@protomaps/basemaps`.
pub const ASSETS_BASE: &str = "https://protomaps.github.io/basemaps-assets/";
/// Style generated by `assets/protomaps/generate.mjs` (@protomaps/basemaps 5.7.2, light, fr).
pub const STYLE: &str = include_str!("../../assets/protomaps/style-light-fr.json");
/// Identifier of the basemap in the pack.
pub const ID: &str = "osm";

/// A daily build of the list.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BuildInfo {
    /// File name, `AAAAMMJJ.pmtiles`.
    pub key: String,
    /// Size of the planet archive.
    pub size: u64,
    /// Upload time.
    pub uploaded: String,
    /// Tile schema version.
    pub version: String,
}

/// Parses the build list (array of `{key, size, uploaded, version}`).
pub fn parse_builds(v: &Value) -> Vec<BuildInfo> {
    let mut out: Vec<BuildInfo> = v
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|b| {
                    Some(BuildInfo {
                        key: b.get("key")?.as_str()?.to_owned(),
                        size: b.get("size").and_then(Value::as_u64).unwrap_or(0),
                        uploaded: b
                            .get("uploaded")
                            .and_then(Value::as_str)
                            .unwrap_or("")
                            .to_owned(),
                        version: b
                            .get("version")
                            .and_then(Value::as_str)
                            .unwrap_or("")
                            .to_owned(),
                    })
                })
                .filter(|b| b.key.ends_with(".pmtiles"))
                .collect()
        })
        .unwrap_or_default();
    out.sort_by(|a, b| a.key.cmp(&b.key));
    out
}

/// Build `AAAAMMJJ`, or the latest one.
pub fn select_build(dl: &Downloader, wanted: Option<&str>) -> Result<BuildInfo> {
    let list: Value = dl
        .fetch(&Request::get(SOURCE, BUILDS_URL).max_age(Duration::from_secs(6 * 3600)))?
        .json()?;
    let builds = parse_builds(&list);
    match wanted {
        Some(w) => {
            let key = format!("{w}.pmtiles");
            builds
                .into_iter()
                .find(|b| b.key == key)
                .ok_or_else(|| Error::Pack(format!("Protomaps build {key} not in {BUILDS_URL}")))
        }
        None => builds
            .into_iter()
            .next_back()
            .ok_or_else(|| Error::Pack(format!("no build in {BUILDS_URL}"))),
    }
}

/// Cached extract of a site (`data/cache/protomaps/extracts/<site>-<build>-z<zoom>.pmtiles`),
/// made if absent.
pub fn cached_extract(
    site: &Site,
    layout: &DataLayout,
    dl: &Downloader,
    build: &BuildInfo,
    maxzoom: u8,
) -> Result<PathBuf> {
    let dir = layout.cache_dir(SOURCE)?.join("extracts");
    create_dir(&dir)?;
    let stem = build.key.trim_end_matches(".pmtiles");
    let b = site.bbox;
    let path = dir.join(format!(
        "{}-{stem}-z{maxzoom}-{}_{}_{}_{}.pmtiles",
        site.id, b.west, b.south, b.east, b.north
    ));
    if !path.is_file() {
        let tmp = path.with_extension("pmtiles.part");
        let url = format!("{BUILD_BASE}{}", build.key);
        let t = std::time::Instant::now();
        let s: ExtractStats = crate::build::extract::extract(
            &HttpRanges {
                dl,
                source: SOURCE,
                url: &url,
            },
            site.bbox,
            maxzoom,
            &tmp,
        )?;
        tracing::info!(
            site = site.id,
            url,
            ?s,
            seconds = t.elapsed().as_secs_f64(),
            "Protomaps extract"
        );
        std::fs::rename(&tmp, &path).map_err(|e| Error::io(&tmp, e))?;
    }
    Ok(path)
}

/// Builds the OSM basemap into `root/basemap/`.
pub fn build(
    site: &Site,
    layout: &DataLayout,
    dl: &Downloader,
    root: &Path,
    wanted_build: Option<&str>,
    maxzoom: u8,
) -> Result<Basemap> {
    let build = select_build(dl, wanted_build)?;
    let extract = cached_extract(site, layout, dl, &build, maxzoom)?;
    let archive_rel = format!("basemap/{ID}.pmtiles");
    let archive_bytes = copy_file(&extract, &root.join(&archive_rel))?;
    let tiles = TileArchive::open(root.join(&archive_rel))?;
    let (minzoom, maxz) = tiles.zoom_range();

    let style: Value =
        serde_json::from_str(STYLE).map_err(|e| Error::json("protomaps style", e))?;
    let dir = root.join("basemap").join(ID);
    write_bytes(&dir.join("style.json"), STYLE.as_bytes())?;
    // Devanagari only labels Indian names; not stored.
    let stacks = assets::fontstacks(&style)
        .into_iter()
        .filter(|s| !s.contains("Devanagari"))
        .collect();
    assets::fetch_glyphs(
        dl,
        ASSETS_SOURCE,
        &format!("{ASSETS_BASE}fonts/{{fontstack}}/{{range}}.pbf"),
        &stacks,
        &dir.join("fonts"),
    )?;
    assets::fetch_sprite(
        dl,
        ASSETS_SOURCE,
        &format!("{ASSETS_BASE}sprites/v4/light"),
        &dir.join("sprites"),
        "light",
    )?;
    let bytes = archive_bytes + dir_size(&dir)?;
    let date = build.key.trim_end_matches(".pmtiles");
    let data_date = if date.len() == 8 {
        format!("{}-{}-{}", &date[..4], &date[4..6], &date[6..])
    } else {
        date.to_owned()
    };
    Ok(Basemap {
        id: ID.to_owned(),
        title: "OpenStreetMap (Protomaps)".to_owned(),
        tiles: archive_rel,
        style: format!("basemap/{ID}/style.json"),
        minzoom,
        maxzoom: maxz,
        tile_count: tiles.addressed_tiles().unwrap_or(0),
        bytes,
        data_date: Some(data_date),
        sources: vec![
            source(
                &format!(
                    "Protomaps, build quotidien {} (schéma {})",
                    build.key, build.version
                ),
                &format!("{BUILD_BASE}{}", build.key),
                "ODbL 1.0 (Produced Work d'OpenStreetMap)",
                "© les contributeurs d'OpenStreetMap, Protomaps",
            ),
            source(
                "Style @protomaps/basemaps 5.7.2 (light, fr), polices et icônes basemaps-assets",
                ASSETS_BASE,
                "BSD-3-Clause (style) ; polices Noto : SIL OFL 1.1",
                "Protomaps",
            ),
        ],
        notes: vec![
            format!(
                "Extrait par requêtes partielles (skimap_pack::build::extract) de {BUILD_BASE}{} : emprise du site, zooms {minzoom} à {maxz}.",
                build.key
            ),
            format!(
                "Glyphes : plages {} seulement.",
                assets::GLYPH_RANGES.join(", ")
            ),
        ],
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn latest_build_is_the_last_key() {
        let v = json!([
            {"key": "20261113.pmtiles", "size": 2, "uploaded": "u2", "version": "4.15.2"},
            {"key": "20261114.pmtiles", "size": 3, "uploaded": "u3", "version": "4.15.2"},
            {"key": "20261112.pmtiles", "size": 1, "uploaded": "u1", "version": "4.15.2"},
            {"key": "README.txt"}
        ]);
        let b = parse_builds(&v);
        assert_eq!(b.len(), 3);
        assert_eq!(b.last().unwrap().key, "20261114.pmtiles");
    }

    #[test]
    fn embedded_style_points_to_the_pack() {
        let s: Value = serde_json::from_str(STYLE).unwrap();
        assert_eq!(
            s["sources"]["protomaps"]["url"],
            "pmtiles://basemap/osm.pmtiles"
        );
        assert_eq!(s["glyphs"], "basemap/osm/fonts/{fontstack}/{range}.pbf");
        let stacks = assets::fontstacks(&s);
        assert!(stacks.contains("Noto Sans Regular"));
    }
}

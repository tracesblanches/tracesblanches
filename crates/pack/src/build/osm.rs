/// Downloader source of the build list.
pub const SOURCE: &str = "protomaps";
/// Downloader source of the style assets (GitHub Pages).
pub const ASSETS_SOURCE: &str = "protomaps-assets";
/// List of the daily builds.
pub const BUILDS_URL: &str = "https://build-metadata.protomaps.dev/builds.json";
/// Base URL of the builds.
pub const BUILD_BASE: &str = "https://build.protomaps.com/";
/// Fonts and sprites of `@protomaps/basemaps`.
pub const ASSETS_BASE: &str = "https://protomaps.github.io/basemaps-assets/";
/// Style generated by `assets/protomaps/generate.mjs` (@protomaps/basemaps 5.7.2, light, fr).
pub const STYLE: &str = include_str!("../../assets/protomaps/style-light-fr.json");
/// Identifier of the basemap in the pack.
pub const ID: &str = "osm";
/// A newer build replaces the one in use at the latest this many days after it, even
/// when the site box did not change: the basemap is at most a week behind OSM.
pub const MAX_AGE_DAYS: i64 = 7;
/// A newer build replaces the one in use as soon as this many tiles of the highest zoom
/// (those cover the site box) differ from it. One edit (a track, a few buildings)
/// touched 1 to 9 tiles of a site; 16 tiles between builds 20261115 and 20261116 for one
/// site are a mapping session in its box. A count, not a share of the box (5 % before,
/// #160): an adoption cost the patch of the wide tiles of zooms 2 to 10 whatever the
/// box (0.4 to 3.4 MB, before the extract started at [`crate::OSM_MINZOOM`]), and 5 % of
/// the 56 tiles of a small box (3 tiles, one edit) made ten sites adopt build 20261118. Smaller edits add up against the build in use, and
/// wait at most [`MAX_AGE_DAYS`]; the trails of the pack come from their own daily OSM
/// layers.
pub const CHANGED_TILES: u64 = 10;

/// A daily build of the list.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BuildInfo {
    /// File name, `AAAAMMJJ.pmtiles`.
    pub key: String,
    /// Size of the planet archive.
    pub size: u64,
    /// Upload time.
    pub uploaded: String,
    /// Tile schema version.
    pub version: String,
}

/// Parses the build list (array of `{key, size, uploaded, version}`).
pub fn parse_builds(v: &Value) -> Vec<BuildInfo> {
    let mut out: Vec<BuildInfo> = v
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|b| {
                    Some(BuildInfo {
                        key: b.get("key")?.as_str()?.to_owned(),
                        size: b.get("size").and_then(Value::as_u64).unwrap_or(0),
                        uploaded: b
                            .get("uploaded")
                            .and_then(Value::as_str)
                            .unwrap_or("")
                            .to_owned(),
                        version: b
                            .get("version")
                            .and_then(Value::as_str)
                            .unwrap_or("")
                            .to_owned(),
                    })
                })
                .filter(|b| b.key.ends_with(".pmtiles"))
                .collect()
        })
        .unwrap_or_default();
    out.sort_by(|a, b| a.key.cmp(&b.key));
    out
}

/// Build `AAAAMMJJ`, or the latest one.
pub fn select_build(dl: &Downloader, wanted: Option<&str>) -> Result<BuildInfo> {
    let list: Value = dl
        .fetch(&Request::get(SOURCE, BUILDS_URL).max_age(Duration::from_secs(6 * 3600)))?
        .json()?;
    let builds = parse_builds(&list);
    match wanted {
        Some(w) => {
            let key = format!("{w}.pmtiles");
            builds
                .into_iter()
                .find(|b| b.key == key)
                .ok_or_else(|| Error::Pack(format!("Protomaps build {key} not in {BUILDS_URL}")))
        }
        None => builds
            .into_iter()
            .next_back()
            .ok_or_else(|| Error::Pack(format!("no build in {BUILDS_URL}"))),
    }
}

/// Directory of the cached extracts.
fn extracts_dir(layout: &DataLayout) -> Result<PathBuf> {
    let dir = layout.cache_dir(SOURCE)?.join("extracts");
    create_dir(&dir)?;
    Ok(dir)
}

/// Box of a site in the extract names, `<west>_<south>_<east>_<north>`.
fn box_name(b: BBox) -> String {
    format!("{}_{}_{}_{}", b.west, b.south, b.east, b.north)
}

/// Zooms of the extracts in their names: `z<max>` from zoom 0 (the only form before
/// [`crate::OSM_MINZOOM`]), `z<min>-<max>` otherwise.
fn zoom_tag(zooms: (u8, u8)) -> String {
    match zooms {
        (0, max) => format!("z{max}"),
        (min, max) => format!("z{min}-{max}"),
    }
}

/// Path of the cached extract of a build, `<site>-<build>-<zooms>-<box>.pmtiles`
/// ([`zoom_tag`]).
fn extract_path(dir: &Path, site: &Site, key: &str, zooms: (u8, u8)) -> PathBuf {
    let stem = key.trim_end_matches(".pmtiles");
    dir.join(format!(
        "{}-{stem}-{}-{}.pmtiles",
        site.id,
        zoom_tag(zooms),
        box_name(site.bbox)
    ))
}

/// Cached extract of a site at zooms `zooms.0..=zooms.1`
/// (`data/cache/protomaps/extracts/<site>-<build>-<zooms>-<box>.pmtiles`), made if absent.
pub fn cached_extract(
    site: &Site,
    layout: &DataLayout,
    dl: &Downloader,
    build: &BuildInfo,
    zooms: (u8, u8),
) -> Result<PathBuf> {
    let path = extract_path(&extracts_dir(layout)?, site, &build.key, zooms);
    if !path.is_file() {
        let tmp = path.with_extension("pmtiles.part");
        let url = format!("{BUILD_BASE}{}", build.key);
        let t = std::time::Instant::now();
        let s: ExtractStats = crate::build::extract::extract(
            &HttpRanges {
                dl,
                source: SOURCE,
                url: &url,
            },
            site.bbox,
            zooms,
            &tmp,
        )?;
        tracing::info!(
            site = site.id,
            url,
            ?s,
            seconds = t.elapsed().as_secs_f64(),
            "Protomaps extract"
        );
        std::fs::rename(&tmp, &path).map_err(|e| Error::io(&tmp, e))?;
    }
    Ok(path)
}

/// Tiles of the highest zoom of the box that differ between two extracts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct BoxChange {
    /// Zoom compared: the highest of the newer extract.
    pub zoom: u8,
    /// Tiles of the box at that zoom.
    pub tiles: u64,
    /// Tiles whose contents differ, tiles present in one extract only included.
    pub changed: u64,
}

impl BoxChange {
    /// Share of the tiles that changed.
    pub fn share(&self) -> f64 {
        if self.tiles == 0 {
            0.0
        } else {
            self.changed as f64 / self.tiles as f64
        }
    }
}

/// Compares the tiles of `bbox` at the highest zoom read from the latest build
/// (`newer`, up to `maxzoom`: only those tiles, their leaf directories and data are read,
/// not the extract of the whole box) with the extract in use `older`, after
/// decompression.
pub fn box_change(
    older: &TileArchive,
    newer: &mut Archive<'_>,
    bbox: BBox,
    maxzoom: u8,
) -> Result<BoxChange> {
    let zoom = maxzoom.min(newer.header().zooms.1);
    let compression = newer.header().tile_compression;
    let tiles = newer.tiles_at(bbox, zoom)?;
    let mut out = BoxChange {
        zoom,
        tiles: 0,
        changed: 0,
    };
    for (z, x, y) in tiles_covering(bbox, zoom, zoom) {
        out.tiles += 1;
        let (a, b) = (older.raw_tile(z, x, y)?, tiles.get(&(z, x, y)));
        let differ = match (&a, b) {
            (Some(a), Some(b)) => {
                a != b && older.tile(z, x, y)? != Some(decompress_tile(b, compression)?)
            }
            (None, None) => false,
            _ => true,
        };
        out.changed += u64::from(differ);
    }
    Ok(out)
}

/// Why the extract of the latest build was adopted, or the one in use kept.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Decision {
    /// No build in use (first build, or its extract left the cache): adopted.
    First,
    /// The latest build is the one in use.
    Same,
    /// The tile schema changed: adopted.
    Schema,
    /// The build asked for is older than the one in use: adopted.
    Older,
    /// The build in use is [`MAX_AGE_DAYS`] older than the latest one, or more: adopted.
    Age,
    /// [`CHANGED_TILES`] box tiles changed, or more: adopted.
    Changed,
    /// The box barely changed and the build in use is recent: kept.
    Kept,
}

impl Decision {
    /// Whether the extract of the latest build is used.
    pub fn adopts(self) -> bool {
        self != Decision::Kept
    }
}

/// Date of a build key `AAAAMMJJ.pmtiles`.
fn build_date(key: &str) -> Option<chrono::NaiveDate> {
    chrono::NaiveDate::parse_from_str(key.trim_end_matches(".pmtiles"), "%Y%m%d").ok()
}

/// Whether the latest build `latest` replaces the build in use `current`. `change`: the
/// box tiles of `latest` against the extract in use, read only when the other rules do
/// not decide ([`needs_comparison`]); `None` there adopts.
pub fn decide(
    current: Option<&BuildInfo>,
    latest: &BuildInfo,
    change: Option<BoxChange>,
) -> Decision {
    let Some(cur) = current else {
        return Decision::First;
    };
    if cur.key == latest.key {
        return Decision::Same;
    }
    if cur.version != latest.version {
        return Decision::Schema;
    }
    match (build_date(&cur.key), build_date(&latest.key)) {
        (Some(a), Some(b)) if b < a => return Decision::Older,
        (Some(a), Some(b)) if (b - a).num_days() < MAX_AGE_DAYS => {}
        // Older than the limit, or keys that are not dates (no age known).
        _ => return Decision::Age,
    }
    match change {
        Some(c) if c.changed < CHANGED_TILES => Decision::Kept,
        _ => Decision::Changed,
    }
}

/// Whether [`decide`] reads the box comparison.
pub fn needs_comparison(current: Option<&BuildInfo>, latest: &BuildInfo) -> bool {
    let unchanged = BoxChange {
        zoom: 0,
        tiles: 0,
        changed: 0,
    };
    decide(current, latest, Some(unchanged)) == Decision::Kept
}

/// The extract used by the pack.
#[derive(Debug, Clone)]
pub struct Chosen {
    /// Build of the extract: its date is the date shown.
    pub build: BuildInfo,
    /// The extract.
    pub path: PathBuf,
    /// The latest build, compared with the one in use.
    pub latest: BuildInfo,
    /// Box tiles of the latest build against the one in use, when compared.
    pub change: Option<BoxChange>,
    /// Decision.
    pub decision: Decision,
}

/// File of the build in use of a site box, `<site>-<zooms>-<box>.current.json`
/// ([`zoom_tag`]).
fn state_path(dir: &Path, site: &Site, zooms: (u8, u8)) -> PathBuf {
    dir.join(format!(
        "{}-{}-{}.current.json",
        site.id,
        zoom_tag(zooms),
        box_name(site.bbox)
    ))
}

/// The build in use recorded in `state` and its extract, when that extract is still in
/// the cache.
fn read_state(
    dir: &Path,
    site: &Site,
    state: &Path,
    zooms: (u8, u8),
) -> Result<Option<(BuildInfo, PathBuf)>> {
    match std::fs::read(state) {
        Ok(b) => {
            let build: BuildInfo = serde_json::from_slice(&b)
                .map_err(|e| Error::json(state.display().to_string(), e))?;
            let path = extract_path(dir, site, &build.key, zooms);
            Ok(path.is_file().then_some((build, path)))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(Error::io(state, e)),
    }
}

/// The extract the pack uses (zooms `zooms.0..=zooms.1`): the one of the build in use,
/// recorded in `extracts/<site>-<zooms>-<box>.current.json`, or the one of `latest` when
/// [`decide`]
/// adopts it (then recorded in its place). The latest build is read by range requests
/// ([`HttpRanges`]); first, once per process and latest build, the cache of the builds
/// that are neither in use nor the latest is removed ([`purge`]).
pub fn current_extract(
    site: &Site,
    layout: &DataLayout,
    dl: &Downloader,
    latest: &BuildInfo,
    zooms: (u8, u8),
) -> Result<Chosen> {
    purge_once(layout, latest)?;
    let url = format!("{BUILD_BASE}{}", latest.key);
    let src = HttpRanges {
        dl,
        source: SOURCE,
        url: &url,
    };
    current_extract_from(site, layout, latest, zooms, &src)
}

/// [`current_extract`] with the latest build read from `src`.
///
/// When the build in use must be compared with the latest one ([`needs_comparison`]),
/// only the tiles of the box at the highest zoom are read from the latest build
/// ([`box_change`]); its extract of the whole box is read (the tiles already read are
/// not read again) and written only when it is adopted. Before (X26), the whole extract
/// of every new build was read for every site to be compared, and kept: 26 MB a day for
/// eight sites, all of it for builds kept aside (#164).
pub fn current_extract_from(
    site: &Site,
    layout: &DataLayout,
    latest: &BuildInfo,
    zooms: (u8, u8),
    src: &dyn RangeSource,
) -> Result<Chosen> {
    let dir = extracts_dir(layout)?;
    let state = state_path(&dir, site, zooms);
    let current = read_state(&dir, site, &state, zooms)?;
    if current.is_none() && zooms.0 != 0 {
        // The extract from zoom 0 in use before `OSM_MINZOOM`: no longer read (its low
        // zooms are not in the pack), removed with its state so that [`purge`] does not
        // keep it as a build in use. The latest build is adopted from `zooms.0`.
        let legacy = (0, zooms.1);
        let old_state = state_path(&dir, site, legacy);
        if let Some((_, old)) = read_state(&dir, site, &old_state, legacy)? {
            remove_file(&old)?;
        }
        remove_file(&old_state)?;
    }
    let mut archive: Option<Archive<'_>> = None;
    let change = match &current {
        Some((cur, cur_path)) if needs_comparison(Some(cur), latest) => {
            let a = archive.insert(Archive::open(src)?);
            Some(box_change(
                &TileArchive::open(cur_path)?,
                a,
                site.bbox,
                zooms.1,
            )?)
        }
        _ => None,
    };
    let decision = decide(current.as_ref().map(|c| &c.0), latest, change);
    let (build, path) = match current {
        Some(c) if !decision.adopts() => c,
        previous => {
            let path = extract_path(&dir, site, &latest.key, zooms);
            if !path.is_file() {
                let a = match archive.as_mut() {
                    Some(a) => a,
                    None => archive.insert(Archive::open(src)?),
                };
                let t = std::time::Instant::now();
                let s = a.extract(site.bbox, zooms, &path)?;
                tracing::info!(
                    site = site.id,
                    build = latest.key,
                    ?s,
                    seconds = t.elapsed().as_secs_f64(),
                    "Protomaps extract"
                );
            }
            // The extract replaced is no longer in use: removed (the pack has its copy).
            if let Some((_, old)) = previous
                && old != path
            {
                remove_file(&old)?;
            }
            (latest.clone(), path)
        }
    };
    if decision.adopts() && decision != Decision::Same {
        let body = serde_json::to_vec_pretty(&build)
            .map_err(|e| Error::json("Protomaps build in use", e))?;
        write_bytes(&state, &body)?;
    }
    let chosen = Chosen {
        build,
        path,
        latest: latest.clone(),
        change,
        decision,
    };
    tracing::info!(
        site = site.id,
        in_use = chosen.build.key,
        latest = latest.key,
        change = ?chosen.change,
        decision = ?chosen.decision,
        reads = ?archive.as_ref().map(Archive::reads),
        "Protomaps build"
    );
    Ok(chosen)
}

fn remove_file(p: &Path) -> Result<u64> {
    let bytes = std::fs::metadata(p).map_or(0, |m| m.len());
    match std::fs::remove_file(p) {
        Ok(()) => Ok(bytes),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(0),
        Err(e) => Err(Error::io(p, e)),
    }
}

/// What [`purge`] removed from the Protomaps cache.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize)]
pub struct Purged {
    /// Site extracts removed.
    pub extracts: usize,
    /// Their bytes.
    pub extract_bytes: u64,
    /// Range entries of the downloader removed (body and metadata).
    pub entries: usize,
    /// Bytes of their bodies.
    pub entry_bytes: u64,
}

/// `<site>-<stem>`, `z<zoom>-<box>` of an extract or state name without its extension:
/// split at the last `-z<digits>-` (a box holds digits, `.`, `_` and `-`, never a `z`).
fn split_zoom(name: &str) -> Option<(&str, &str)> {
    let b = name.as_bytes();
    (0..b.len().saturating_sub(2)).rev().find_map(|i| {
        if b[i] != b'-' || b[i + 1] != b'z' {
            return None;
        }
        let digits = b[i + 2..].iter().take_while(|c| c.is_ascii_digit()).count();
        (digits > 0 && b.get(i + 2 + digits) == Some(&b'-')).then(|| (&name[..i], &name[i + 1..]))
    })
}

/// Removes from the Protomaps cache what is neither the build in use nor the latest
/// (#164). Site extracts: those of a build that is not in use for their site box (any
/// `*.current.json` of `extracts/`) nor `latest` (a kept build was extracted whole every
/// day before the comparison read only the highest zoom). Range entries of the
/// downloader: those of every build but `latest`. The pieces of a build in use are never
/// read again (its tiles are in its extracts, and a site whose extract left the cache
/// adopts the latest build, [`Decision::First`]); they were kept beside the extracts,
/// 545 MB for one build of 268 sites, and those of every older build stayed. The France
/// extract (`france/`) and the build list are left alone.
pub fn purge(layout: &DataLayout, latest: &BuildInfo) -> Result<Purged> {
    let cache = layout.cache_dir(SOURCE)?;
    let dir = extracts_dir(layout)?;
    let mut in_use: std::collections::BTreeSet<String> = Default::default();
    let mut names = Vec::new();
    for e in std::fs::read_dir(&dir).map_err(|e| Error::io(&dir, e))? {
        let e = e.map_err(|e| Error::io(&dir, e))?;
        names.push(e.file_name().to_string_lossy().into_owned());
    }
    for n in &names {
        let Some(stem) = n.strip_suffix(".current.json") else {
            continue;
        };
        let p = dir.join(n);
        let Ok(b) =
            serde_json::from_slice::<BuildInfo>(&std::fs::read(&p).map_err(|e| Error::io(&p, e))?)
        else {
            continue;
        };
        if let Some((site, rest)) = split_zoom(stem) {
            let key = b.key.trim_end_matches(".pmtiles");
            in_use.insert(format!("{site}-{key}-{rest}.pmtiles"));
        }
    }
    let latest_stem = format!("-{}", latest.key.trim_end_matches(".pmtiles"));
    let mut out = Purged::default();
    for n in &names {
        let Some(stem) = n.strip_suffix(".pmtiles") else {
            continue;
        };
        let latest_one = split_zoom(stem).is_some_and(|(s, _)| s.ends_with(&latest_stem));
        if !latest_one && !in_use.contains(n) {
            out.extract_bytes += remove_file(&dir.join(n))?;
            out.extracts += 1;
        }
    }
    let latest_url = format!("{BUILD_BASE}{}", latest.key);
    for e in std::fs::read_dir(&cache).map_err(|e| Error::io(&cache, e))? {
        let p = e.map_err(|e| Error::io(&cache, e))?.path();
        if p.extension().is_none_or(|x| x != "json") || !p.is_file() {
            continue;
        }
        let Some(url) = std::fs::read(&p)
            .ok()
            .and_then(|b| serde_json::from_slice::<Value>(&b).ok())
            .and_then(|v| v.get("url").and_then(Value::as_str).map(str::to_owned))
        else {
            continue;
        };
        if url.starts_with(BUILD_BASE) && url != latest_url {
            out.entry_bytes += remove_file(&p.with_extension("body"))?;
            remove_file(&p)?;
            out.entries += 1;
        }
    }
    Ok(out)
}

/// [`purge`] once per process, cache and latest build, before the first read of a build.
fn purge_once(layout: &DataLayout, latest: &BuildInfo) -> Result<()> {
    static DONE: std::sync::Mutex<Vec<(PathBuf, String)>> = std::sync::Mutex::new(Vec::new());
    let mut done = DONE
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    let k = (layout.cache_root(), latest.key.clone());
    if done.contains(&k) {
        return Ok(());
    }
    let p = purge(layout, latest)?;
    tracing::info!(latest = latest.key, ?p, "Protomaps cache purged");
    done.push(k);
    Ok(())
}

/// Key of the OSM basemap of a site ([`crate::build::parts`]): the latest build, the
/// build in use (`<site>-<zooms>-<box>.current.json` and whether its extract is still
/// in the cache), the box, the zooms and the style. Unchanged while no new Protomaps build
/// appears and the build in use stays: the pack then takes the basemap of the previous
/// pack without reading the extracts again. Made after a build, the key already holds
/// the build it adopted.
pub fn part_key(
    site: &Site,
    layout: &DataLayout,
    latest: &BuildInfo,
    zooms: (u8, u8),
) -> Result<String> {
    let dir = extracts_dir(layout)?;
    let state = state_path(&dir, site, zooms);
    let current = match std::fs::read(&state) {
        Ok(b) => {
            let present = serde_json::from_slice::<BuildInfo>(&b)
                .is_ok_and(|c| extract_path(&dir, site, &c.key, zooms).is_file());
            format!("{} {present}", crate::update::sha256_hex(&b))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => "none".to_owned(),
        Err(e) => return Err(Error::io(&state, e)),
    };
    let latest = serde_json::to_string(latest).map_err(|e| Error::json("Protomaps build", e))?;
    let mut k = crate::build::parts::Key::new(&format!("basemap:{ID}"));
    k.add("latest", &latest)
        .add("current", &current)
        .add("box", &box_name(site.bbox))
        .add("minzoom", &zooms.0.to_string())
        .add("maxzoom", &zooms.1.to_string())
        .add("style", &crate::update::sha256_hex(STYLE.as_bytes()))
        .add("assets", ASSETS_BASE);
    Ok(k.finish())
}

/// Builds the OSM basemap (zooms `zooms.0..=zooms.1` of the site box) into
/// `root/basemap/`.
pub fn build(
    site: &Site,
    layout: &DataLayout,
    dl: &Downloader,
    root: &Path,
    wanted_build: Option<&str>,
    zooms: (u8, u8),
) -> Result<Basemap> {
    build_from(
        site,
        layout,
        dl,
        root,
        &select_build(dl, wanted_build)?,
        zooms,
    )
}

/// [`build`] with the latest build already listed.
pub fn build_from(
    site: &Site,
    layout: &DataLayout,
    dl: &Downloader,
    root: &Path,
    latest: &BuildInfo,
    zooms: (u8, u8),
) -> Result<Basemap> {
    let chosen = current_extract(site, layout, dl, latest, zooms)?;
    let build = &chosen.build;
    let archive_rel = format!("basemap/{ID}.pmtiles");
    let archive_bytes = copy_file(&chosen.path, &root.join(&archive_rel))?;
    let tiles = TileArchive::open(root.join(&archive_rel))?;
    let (minzoom, maxz) = tiles.zoom_range();

    let style: Value =
        serde_json::from_str(STYLE).map_err(|e| Error::json("protomaps style", e))?;
    let dir = root.join("basemap").join(ID);
    write_bytes(&dir.join("style.json"), STYLE.as_bytes())?;
    // Devanagari only labels Indian names; not stored.
    let stacks = assets::fontstacks(&style)
        .into_iter()
        .filter(|s| !s.contains("Devanagari"))
        .collect();
    assets::fetch_glyphs(
        dl,
        ASSETS_SOURCE,
        &format!("{ASSETS_BASE}fonts/{{fontstack}}/{{range}}.pbf"),
        &stacks,
        &dir.join("fonts"),
    )?;
    assets::fetch_sprite(
        dl,
        ASSETS_SOURCE,
        &format!("{ASSETS_BASE}sprites/v4/light"),
        &dir.join("sprites"),
        "light",
    )?;
    let bytes = archive_bytes + dir_size(&dir)?;
    let date = build.key.trim_end_matches(".pmtiles");
    let data_date = if date.len() == 8 {
        format!("{}-{}-{}", &date[..4], &date[4..6], &date[6..])
    } else {
        date.to_owned()
    };
    Ok(Basemap {
        id: ID.to_owned(),
        title: "OpenStreetMap (Protomaps)".to_owned(),
        tiles: archive_rel,
        style: format!("basemap/{ID}/style.json"),
        minzoom,
        maxzoom: maxz,
        tile_count: tiles.addressed_tiles().unwrap_or(0),
        bytes,
        data_date: Some(data_date),
        sources: vec![
            source(
                &format!(
                    "Protomaps, build quotidien {} (schéma {})",
                    build.key, build.version
                ),
                &format!("{BUILD_BASE}{}", build.key),
                "ODbL 1.0 (Produced Work d'OpenStreetMap)",
                "© les contributeurs d'OpenStreetMap, Protomaps",
            ),
            source(
                "Style @protomaps/basemaps 5.7.2 (light, fr), polices et icônes basemaps-assets",
                ASSETS_BASE,
                "BSD-3-Clause (style) ; polices Noto : SIL OFL 1.1",
                "Protomaps",
            ),
        ],
        notes: vec![
            format!(
                "Extrait par requêtes partielles (skimap_pack::build::extract) de {BUILD_BASE}{} : emprise du site, zooms {minzoom} à {maxz}.",
                build.key
            ),
            renewal_note(&chosen),
            format!(
                "Glyphes : plages {} seulement.",
                assets::GLYPH_RANGES.join(", ")
            ),
        ],
    })
}

/// Manifest note: which build is in use and why.
fn renewal_note(c: &Chosen) -> String {
    let rule = format!(
        "le fond n'est renouvelé que quand {CHANGED_TILES} tuiles de l'emprise au zoom maximal ont changé, ou {MAX_AGE_DAYS} jours après le build en usage"
    );
    let compared = c.change.map(|ch| {
        let s = if ch.changed > 1 { "s" } else { "" };
        format!(
            "{} tuile{s} sur {} différente{s} au zoom {}",
            ch.changed, ch.tiles, ch.zoom
        )
    });
    let why = match c.decision {
        Decision::Kept => format!(
            "build {} conservé : dernier build {} comparé, {}",
            c.build.key,
            c.latest.key,
            compared.unwrap_or_default()
        ),
        Decision::Changed => format!(
            "build {} adopté : {}",
            c.build.key,
            compared.unwrap_or_default()
        ),
        Decision::Age => format!("build {} adopté : build précédent trop ancien", c.build.key),
        Decision::Schema => format!("build {} adopté : schéma des tuiles changé", c.build.key),
        Decision::Older => format!("build {} demandé explicitement", c.build.key),
        Decision::First | Decision::Same => format!("build {} en usage", c.build.key),
    };
    format!("Mises à jour : {why} ; {rule}.")
}

